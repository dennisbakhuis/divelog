#!/usr/bin/env node
/**
 * Write the OG card fonts as a base64 data module, so the OG renderer needs no
 * `?inline` import and survives bundling and `svelte-package` alike.
 * Usage: node scripts/og-fonts.mjs [--check]
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const fontDir = join(root, 'src/lib/og/fonts');
const outFile = join(root, 'src/lib/og/font-data.ts');
const fonts = ['SpaceGrotesk-Bold.ttf', 'SpaceGrotesk-Medium.ttf', 'JetBrainsMono-Regular.ttf'];

const entries = fonts
  .map((name) => `  '${name}':\n    '${readFileSync(join(fontDir, name)).toString('base64')}',`)
  .join('\n');
const source = `/** Generated by scripts/og-fonts.mjs from ./fonts; do not edit. */
export const OG_FONTS: Record<string, string> = {
${entries}
};
`;

if (process.argv.includes('--check')) {
  if (!existsSync(outFile) || readFileSync(outFile, 'utf8') !== source) {
    console.error('font-data.ts is out of date. Run "pnpm og-fonts".');
    process.exit(1);
  }
  console.log('font-data.ts is up to date.');
} else {
  writeFileSync(outFile, source);
  console.log(`Wrote ${outFile}`);
}
